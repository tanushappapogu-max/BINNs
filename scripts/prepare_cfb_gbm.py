"""Tidy per-scan CFB-GBM tumor volumes from the official TCIA metadata tables.

Builds one row per patient and timepoint from two small TSVs on TCIA, so the
208 GB image package is not needed:

* ``CFB-GBM_rano_criteria``: GTV size (cm³ = mL) at t0, t1 and t2;
* ``CFB-GBM_mri_availability``: weeks from t0 to each timepoint;
* ``CFB-GBM_treatment_imaging_availability``: whether each GTV was drawn by a
  radiation oncologist or generated by the released nnU-Net model.

The output has the columns ``gbm-ceiling`` reads (``patient``, ``day``,
``volume_ml``) plus ``timepoint`` and ``gtv_source``. CFB-GBM is not a
confirmatory cohort in this project; see ``docs/cfb_gbm_design_assessment.md``.

Usage:
    uv run --extra analysis python scripts/prepare_cfb_gbm.py
"""

from __future__ import annotations

import argparse
import urllib.request
from pathlib import Path

import pandas as pd

BASE_URL = "https://www.cancerimagingarchive.net/wp-content/uploads/"
FILES = {
    "rano": "CFB-GBM_rano_criteria_v04_20260909.tsv",
    "mri": "CFB-GBM_mri_availability_v02_20260129.tsv",
    "gtv": "CFB-GBM_treatment_imaging_availability_v03_20260619.tsv",
}


def fetch(raw: Path) -> dict[str, pd.DataFrame]:
    raw.mkdir(parents=True, exist_ok=True)
    tables = {}
    for key, name in FILES.items():
        path = raw / name
        if not path.is_file():
            urllib.request.urlretrieve(BASE_URL + name, path)
        tables[key] = pd.read_csv(path, sep="\t")
    return tables


def tidy(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rano, mri, gtv = tables["rano"], tables["mri"], tables["gtv"]
    sizes = rano.melt(
        id_vars="id_patient",
        value_vars=["size_t0 (cm3)", "size_t1 (cm3)", "size_t2 (cm3)"],
        var_name="column",
        value_name="volume_ml",
    ).dropna(subset=["volume_ml"])
    sizes["timepoint"] = sizes.column.str.extract(r"(t\d)", expand=False)
    weeks = mri[["id_patient", "temporality", "time_diff_t0 (weeks)"]].rename(
        columns={"temporality": "timepoint", "time_diff_t0 (weeks)": "weeks"}
    )
    source = gtv[["id_patient", "temporality", "gtv_type"]].rename(
        columns={"temporality": "timepoint", "gtv_type": "gtv_source"}
    )
    frame = (
        sizes.drop(columns="column")
        .merge(weeks, on=["id_patient", "timepoint"], how="left")
        .merge(source, on=["id_patient", "timepoint"], how="left")
        .dropna(subset=["weeks"])
    )
    frame["patient"] = "CFB-" + frame.id_patient.astype(str)
    frame["day"] = frame.weeks * 7.0
    columns = ["patient", "timepoint", "day", "volume_ml", "gtv_source"]
    return frame[columns].sort_values(["patient", "day"]).reset_index(drop=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=Path("data/raw/cfb_gbm"))
    parser.add_argument(
        "--output", type=Path, default=Path("outputs/surveillance/cfb_gbm_scan_volumes.csv")
    )
    args = parser.parse_args()
    frame = tidy(fetch(args.raw))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(args.output, index=False)
    complete = frame.groupby("patient").size().eq(3).sum()
    print(
        f"wrote {len(frame)} scans from {frame.patient.nunique()} patients "
        f"({complete} with all three timepoints) to {args.output}"
    )


if __name__ == "__main__":
    main()
